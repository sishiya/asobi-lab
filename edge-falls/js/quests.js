// お題4・5 の「いっしょにつづく」の条件
function questCond(qi, s) {
  if (qi === 3) return L.counts.wolf >= 3 && L.counts.deer >= 10;
  if (qi === 4) return s.grass >= 0.2 && L.counts.deer > 0 && L.counts.wolf > 0 && L.counts.fish > 0;
  return false;
}
