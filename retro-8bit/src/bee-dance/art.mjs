// 花の群れ（パレット 1: 0 こい緑・1 緑・2 白・3 黄）: 32×32 に 10 輪ほど。swap で白い花びらに黄のまん中 ⇄ 黄の花びらに白のまん中
function flowers(seed, swap) {
  const P = swap ? '3' : '2', C = swap ? '2' : '3';
  const fl = Array.from({ length: 14 }, (_, i) => ({ x: 4 + hash(i, 1, seed) * 24, y: 4 + hash(i, 2, seed) * 24, r: 2.6 + hash(i, 3, seed) * 1.3 }));
  return grid(32, 32, (x, y) => {
    for (const f of fl) {
      const dx = x - f.x, dy = y - f.y, d = Math.hypot(dx, dy);
      if (d < 1.0) return C;
      if (d <= f.r) {
        const ang = Math.atan2(dy, dx), pet = Math.cos(ang * 5 + f.x) * 0.5 + 0.5; // 花びら 5 枚（ふちに小さな切れこみ）
        if (d > f.r - 0.6 && pet < 0.25) return '1';
        return P;
      }
    }
    for (const f of fl) if (Math.hypot(x - f.x - 1, y - f.y - 1) <= f.r * 0.9) return '.'; // 草に落ちる影
    return hash(x, y, seed + 3) < 0.06 ? '.' : '1';
  });
}
// 巣箱（パレット 2: 0 こい緑・1 緑・2 わら・3 クリームの照り）: 上から見た、わらで編んだ丸い巣（スケップ）。32×32。外は草、右下に影
const skep = grid(32, 32, (x, y) => {
  const dx = x - 15.5, dy = y - 15.5, d = Math.hypot(dx, dy);
  if (d > 14.5) return Math.hypot(dx - 1.5, dy - 1.5) <= 14.5 ? '.' : '1';
  if (d < 3.4) return '.';                                    // てっぺんの入り口
  if ((d / 2.6) % 1 < 0.3) return '.';                        // わらの巻きのさかい
  const lit = -(dx + dy) / (d + 0.01);
  if (lit > 0.5 && (d / 2.6) % 1 < 0.65) return '3';
  return dx + dy > 14 && (x + y) % 2 ? '.' : '2';
});

