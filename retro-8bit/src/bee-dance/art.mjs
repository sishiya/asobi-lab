const grid = (w, h, f) => Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) => f(x, y)).join(''));
const hash = (x, y, s) => { let n = (x * 374761393 + y * 668265263 + s * 2147483647) | 0; n = (n ^ (n >>> 13)) * 1274126177; return ((n ^ (n >>> 16)) >>> 0) / 4294967296; };
const g8 = (f) => grid(8, 8, f);

// ---------- 巣（パレット 0: 0 こげ茶・1 ろうのかべ・2 はちみつ・3 ふた（クリーム）） ----------
// 1 つの部屋 = 16×16（2×2 の絵）。行ごとに 8 ドットずらして並べる（data.mjs）。部屋の中身は 3 つ: 空・はちみつ・ふた
function cellRoom(kind, seed) {
  // 先のとがった六角（上と下がとがる）。ふち 1 ドットがろうのかべ、外のすみもかべ
  const hex = (x, y) => { const dx = Math.abs(x - 7.5), dy = Math.abs(y - 7.5); return dx <= 6.2 && dy <= 7.2 - dx * 0.55; };
  return grid(16, 16, (x, y) => {
    if (!hex(x, y)) return '1';
    if (!hex(x - 1, y) || !hex(x + 1, y) || !hex(x, y - 1) || !hex(x, y + 1)) return x + y < 15 ? '1' : '.'; // かべのふち（右下は影）
    const dx = x - 7.5, dy = y - 7.5;
    if (kind === 'empty') return dx + dy < -4 ? '.' : '1';                         // 空: 浅いくぼみ（左上のふちだけ影）
    if (kind === 'honey') {
      if (Math.hypot(dx + 2, dy + 2) < 1.6) return '3';                            // つやの光
      return dx + dy > 5 ? '1' : '2';
    }
    // ふた（みつろうでふたをした部屋）: クリームに、ふちの影と小さなでこぼこ
    if (dx + dy > 6) return '2';
    return hash(x, y, seed) < 0.08 ? '2' : '3';
  });
}

// ---------- 花畑（パレット 0: 0 こい緑・1 緑・2 明るい緑・3 黄緑の照り） ----------
// 草: 短い葉の束を散らす。光は左上から（葉の左上がわが明るい）
function grass(s, n, lit = 1) {
  const tufts = Array.from({ length: n }, (_, i) => ({ x: hash(i, 1, s) * 8, y: hash(i, 2, s) * 8, a: hash(i, 3, s) }));
  return g8((x, y) => {
    for (const t of tufts) for (const ox of [-8, 0, 8]) for (const oy of [-8, 0, 8]) {
      const dx = x - t.x - ox, dy = y - t.y - oy;
      // 葉 3 本: 下の根もとから、左・上・右へ
      for (const k of [-0.7, 0, 0.7]) {
        const ex = Math.sin(k + t.a * 0.4) * 3, ey = -3;
        const tt = Math.max(0, Math.min(1, (dx * ex + dy * ey) / (ex * ex + ey * ey)));
        const d = Math.hypot(dx - ex * tt, dy - ey * tt);
        if (d < 0.5) return lit && tt > 0.75 ? '3' : '2';
        if (d < 1.1 && dx - ex * tt > 0) return '.';
      }
    }
    return '1';
  });
}
