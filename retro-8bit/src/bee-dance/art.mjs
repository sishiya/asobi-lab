// ミツバチの おどり のドット絵。1文字 = 1ドット（. = 0 すきとおり／背景の色、1・2・3 = パレットの色）。
// 巣板の六角も、花畑の草も、ダンゴムシのみち（v036）と同じ考え: 8×8 の絵を何種かまぜ、光は左上から、ふちは背景の色へとかす
