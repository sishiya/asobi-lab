// ---------- スプライト（パレット: 0 ハチ / 1 太陽 / 2 しるし / 3 みつのつぶ） ----------
// ハチ（上から見た形。上むきを式で描き、5 つの角度 0・22.5・45・67.5・90 度に回して描く。ほかの向きは裏返し）。
// 1 黒（ふち・しま）・2 黄（毛と腹）・3 白（はね）。frame 1 は はねを少し閉じる
function beeAt(u, v, wing) {
  // u = 右、v = 上（ハチのまん中から。頭が +v）
  const head = Math.hypot(u, v - 4.6) < 1.7;
  const thorax = Math.hypot(u / 2.3, (v - 1.8) / 2.0) < 1;
  const abd = Math.hypot(u / 2.6, (v + 2.6) / 3.6) < 1;
  // はね: 胸から後ろ外へ
  const wa = wing ? 0.55 : 0.85;
  const wingOn = (side) => {
    const ax = side * Math.sin(wa), ay = -Math.cos(wa);
    const px = u - side * 1.2, py = v - 1.8;
    const t = px * ax + py * ay, n = -px * ay + py * ax;
    return t > 0 && t < 6.2 && Math.abs(n) < 1.9 * Math.sin(Math.min(Math.PI, (t / 6.2) * Math.PI) ** 0.7);
  };
  if (head) return Math.hypot(u, v - 4.6) > 1.0 ? '1' : '1';
  if (thorax) return Math.hypot(u / 2.3, (v - 1.8) / 2.0) > 0.78 ? '1' : '2';
  if (abd) {
    if (Math.hypot(u / 2.6, (v + 2.6) / 3.6) > 0.8) return '1';
    const band = (v + 6.2) % 1.9;                            // しま
    return band < 0.75 ? '1' : '2';
  }
  if (wingOn(1) || wingOn(-1)) return '3';
  // 触角
  for (const side of [1, -1]) {
    for (let t = 0; t <= 1; t += 0.1) { const ax = side * (0.5 + t * 1.6), ay = 5.6 + t * 2.0; if (Math.hypot(u - ax, v - ay) < 0.5) return '1'; }
  }
  return '.';
}
function bee(deg, wing) {
  const r = (deg * Math.PI) / 180, c = Math.cos(r), s = Math.sin(r);
  return grid(16, 16, (x, y) => {
    const px = x - 7.5, py = 7.5 - y;              // 画面 → 上が +
    const u = px * c - py * s, v = px * s + py * c; // ハチの向きへ戻す（時計回り deg）
    return beeAt(u, v, wing);
  });
}
// 太陽（パレット 1: 1 だいだい・2 黄・3 白）
const sun = grid(16, 16, (x, y) => {
  const dx = x - 7.5, dy = y - 7.5, d = Math.hypot(dx, dy), a = Math.atan2(dy, dx);
  if (d < 3.6) return dx + dy < -2 ? '3' : '2';
  if (d < 4.6) return '1';
  if (d < 7.4 && Math.cos(a * 8) > 0.7) return d < 6 ? '2' : '1';
  return '.';
});
// しるし（パレット 2: 1 白・2 黒・3 黄）: 輪の点（8×8）と、ねらう所の輪（16×16）
const dot = g8((x, y) => { const d = Math.hypot(x - 3.5, y - 3.5); return d < 1.6 ? '1' : d < 2.6 ? '2' : '.'; });
const target = grid(16, 16, (x, y) => {
  const d = Math.hypot(x - 7.5, y - 7.5);
  if (d > 5.4 && d < 6.6) return Math.abs(x - 7.5) < 1.5 || Math.abs(y - 7.5) < 1.5 ? '.' : '1';
  if (d > 4.6 && d < 7.4) return Math.abs(x - 7.5) < 1.5 || Math.abs(y - 7.5) < 1.5 ? '.' : '2';
  return '.';
});
// みつのつぶ（パレット 3: 1 だいだい・2 黄・3 白）
const drop = g8((x, y) => { const dx = x - 3.5, dy = y - 4; const d = Math.hypot(dx, dy * (dy < 0 ? 0.6 : 1)); return d < 2.2 ? (dx + dy < -1.5 ? '3' : '2') : d < 3 ? '1' : '.'; });
// ダンスの足あと（パレット 2 の黄）
